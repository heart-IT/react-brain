// The service worker, generated at build so it knows the base path, this build's
// version (old caches are dropped on activate) and every topic page.
//   install   cache the app shell: core pages + the hashed assets they reference + data
//   activate  drop old caches, then fetch every topic page in the background
//   fetch     pages: network first, cached copy offline, else offline/
//             /_astro/ (hashed, immutable): cache first
//             everything else in scope (data, pagefind, icons): stale-while-revalidate
import { corpus, siteMeta, href } from '../lib/corpus.js';

export function GET() {
  const { entries } = corpus();
  const CORE = ['', 'doctor/', 'stack/', 'compare/', 'entries/', 'libraries/', 'search/', 'offline/',
    'doctor-data.json', 'palette-data.json', 'compare-data.json', 'console-data.json', 'console.js',
    'manifest.webmanifest', 'icon-192.png', 'brand-64.png', 'favicon-32.png'].map(href);
  const TOPICS = entries.map((e) => href(`entries/${e.slug}/`));
  const assetRe = '(?:href|src)="(' + href('_astro/').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[^"]+)"';
  const src = `// generated by src/pages/sw.js.js — do not edit dist/sw.js
const VERSION = ${JSON.stringify(`${siteMeta().version}-${Date.now().toString(36)}`)};
const BASE = ${JSON.stringify(href(''))};
const CORE = ${JSON.stringify(CORE)};
const TOPICS = ${JSON.stringify(TOPICS)};
const CACHE = 'rb-' + VERSION;
const ASSET = new RegExp(${JSON.stringify(assetRe)}, 'g');

// a hashed asset, and for a script every chunk it imports (those appear only
// inside other scripts, never in the page's HTML)
const IMPORT = /(?:from|import)\\s*["'](\\.{1,2}\\/[^"']+\\.js)["']/g;
async function cacheAsset(cache, url) {
  if (await cache.match(url)) return;
  const res = await fetch(url);
  if (!res.ok) return;
  if (url.endsWith('.js')) {
    const text = await res.clone().text();
    await cache.put(url, res);
    await Promise.all([...text.matchAll(IMPORT)].map((m) => cacheAsset(cache, new URL(m[1], location.origin + url).pathname).catch(() => {})));
  } else await cache.put(url, res);
}

// a page plus the hashed assets it references, so it renders offline
async function cachePage(cache, url) {
  const res = await fetch(url, { cache: 'no-cache' });
  if (!res.ok) return;
  const text = await res.clone().text();
  await cache.put(url, res);
  const assets = [...new Set([...text.matchAll(ASSET)].map((m) => m[1]))];
  await Promise.all(assets.map((a) => cacheAsset(cache, a).catch(() => {})));
}

self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(CORE.map((u) => (u.endsWith('/') ? cachePage(cache, u) : cache.add(u)).catch(() => {})));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('rb-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
    const cache = await caches.open(CACHE);
    for (const u of TOPICS) if (!(await cache.match(u))) await cachePage(cache, u).catch(() => {});
  })());
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (req.method !== 'GET' || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      const cache = await caches.open(CACHE);
      try {
        const res = await fetch(req);
        if (res.ok) cache.put(url.pathname, res.clone());
        return res;
      } catch {
        return (await cache.match(url.pathname, { ignoreVary: true })) || (await cache.match(BASE + 'offline/', { ignoreVary: true })) || Response.error();
      }
    })());
    return;
  }
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // match on the URL alone: pages request scripts/fonts in CORS mode with an Origin
    // header the precache fetch didn't send, and a Vary on the response would miss
    const hit = await cache.match(req, { ignoreVary: true, ignoreSearch: url.pathname.includes('/_astro/') });
    if (hit && url.pathname.includes('/_astro/')) return hit;
    const net = fetch(req).then((res) => { if (res.ok) cache.put(req, res.clone()); return res; });
    if (hit) { e.waitUntil(net.catch(() => {})); return hit; }
    return net;
  })());
});
`;
  return new Response(src, { headers: { 'content-type': 'text/javascript' } });
}
